-- 00054_statement_of_compliance.sql
--
-- Strategic 1 follow-up — Monthly Statement of Compliance.
--
-- Why this table:
--   The Compliance Score (00051) gave the org a "single number that goes
--   up". This table is the second visible payoff: once a month the
--   generate-statement-of-compliance edge function aggregates that
--   month's daily snapshots into a one-row summary, renders a branded
--   PDF, drops it in storage, and emails it to the org's support_email.
--   That PDF is the artifact an FM lead forwards to their insurer /
--   board / lender — "here is our compliance posture for April".
--
-- Lifecycle:
--   - INSERT/UPSERTed by generate-statement-of-compliance, run via
--     pg_cron at 06:00 UTC on the 1st of each month for the previous
--     calendar month.
--   - Idempotent on (organisation_id, period_start) — re-running for
--     the same period overwrites the row (e.g. when an admin clicks
--     "Generate now" to refresh after fixing a snapshot).
--   - Rows are never deleted. The history is the product.
--
-- Notes on the columns:
--   - score_avg / score_min / score_max are aggregated from the daily
--     compliance_score_snapshots in [period_start, period_end]. Stored
--     as smallint (0–100) — same convention as the source table.
--   - breakdown_avg is the per-axis average across the period, captured
--     as jsonb for the same reason as the snapshot table: lets us add /
--     reweight axes without re-migrating.
--   - pdf_url stores the storage path (e.g.
--     statements-of-compliance/{org_id}/{period_start}.pdf), not a
--     signed URL — same convention as certificates.pdf_url. The hook
--     mints a signed URL on demand.

create table if not exists public.statement_of_compliance (
  id              uuid primary key default gen_random_uuid(),
  organisation_id uuid not null references public.organisations(id) on delete cascade,
  -- First and last day of the month the statement covers. Both stored
  -- so the read hook + UI don't need to recompute the range.
  period_start    date not null,
  period_end      date not null,
  -- Aggregates of the daily compliance_score_snapshots in the period.
  -- 0–100 inclusive. Smallint matches the source column.
  score_avg       smallint not null check (score_avg between 0 and 100),
  score_min       smallint not null check (score_min between 0 and 100),
  score_max       smallint not null check (score_max between 0 and 100),
  -- Per-axis average across the period. Same shape as
  -- compliance_score_snapshots.breakdown.
  breakdown_avg   jsonb    not null default '{}'::jsonb,
  -- Storage path inside the statements-of-compliance bucket. Null when
  -- the PDF render leg failed (HTML-only fallback). The hook will
  -- prefer pdf_url and fall back to the signed-URL HTML.
  pdf_url         text,
  -- Set when the summary email actually leaves Resend (or the
  -- equivalent HTML-only "no email config" no-op). Null = unsent.
  email_sent_at   timestamptz,
  created_at      timestamptz not null default now(),

  -- Idempotency — one statement per (org, period). The cron / "Generate
  -- now" button uses upsert(on conflict do update) keyed by this pair.
  unique (organisation_id, period_start)
);

-- Hot read pattern is "give me the most recent N statements for THIS
-- org" — descending by period_start.
create index if not exists statement_of_compliance_org_period_idx
  on public.statement_of_compliance (organisation_id, period_start desc);

-- ---- RLS ----------------------------------------------------------
-- Read-only to org members. INSERT/UPDATE/DELETE only happens from the
-- service role inside the edge function — no client-facing mutation
-- policies needed.

alter table public.statement_of_compliance enable row level security;

create policy "statement_of_compliance_select_org"
  on public.statement_of_compliance for select
  using (
    organisation_id in (
      select organisation_id from public.profiles where id = auth.uid()
    )
  );

comment on table public.statement_of_compliance is
  'Monthly Statement of Compliance — one row per organisation per calendar month. Generated by the generate-statement-of-compliance edge function (pg_cron, 06:00 UTC on the 1st). PDF lives in the statements-of-compliance storage bucket. Strategic 1 follow-up.';

-- ---- Storage ------------------------------------------------------
-- Private bucket; consumers mint short-lived signed URLs on demand.
-- The edge function writes keys as `<organisation_id>/<period_start>.pdf`.

insert into storage.buckets (id, name, public)
values ('statements-of-compliance', 'statements-of-compliance', false)
on conflict (id) do nothing;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'statements_of_compliance_auth_rw'
  ) then
    create policy "statements_of_compliance_auth_rw" on storage.objects
      for all to authenticated
      using (
        bucket_id = 'statements-of-compliance'
        and (storage.foldername(name))[1] in (
          select organisation_id::text from public.profiles where id = auth.uid()
        )
      )
      with check (
        bucket_id = 'statements-of-compliance'
        and (storage.foldername(name))[1] in (
          select organisation_id::text from public.profiles where id = auth.uid()
        )
      );
  end if;
end $$;
