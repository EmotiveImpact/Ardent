#!/usr/bin/env bash
# Copy Ardent's shared code into the mobile app, so Metro never reaches outside
# mobile/:
#   - Core's data model, client interface and mock records (src/data/core)
#   - the design kit from engine/kit: tokens, states, formats, wording (src/kit)
#   - the engine files the one Connection needs (src/engine), so the phone can
#     talk to a running engine or run the engine itself on the demo firm
# Never edit the copies by hand. Run from mobile/.
# Usage: scripts/sync-core.sh [git-ref]   (default: read the repo from disk)
set -euo pipefail
cd "$(dirname "$0")/.."
pairs=(
  "core/src/data/model.ts:src/data/core/model.ts"
  "core/src/data/client.ts:src/data/core/client.ts"
  "core/src/data/mock.ts:src/data/core/mock.ts"
)
for f in tokens states format copy index report; do pairs+=("engine/kit/$f.ts:src/kit/$f.ts"); done
for f in connect engine http-client office platform seed store; do pairs+=("engine/src/$f.ts:src/engine/$f.ts"); done
for p in "${pairs[@]}"; do
  src="${p%%:*}" dest="${p##*:}"
  mkdir -p "$(dirname "$dest")"
  if [[ $# -gt 0 ]]; then git show "$1:$src" > "$dest"; else cp "../$src" "$dest"; fi
  # Metro resolves imports without the .ts suffix, and Core's data sits in data/core here.
  if [[ $dest == src/kit/* || $dest == src/engine/* ]]; then
    sed -i \
      -e "s#'\.\./\.\./core/src/data/\([a-z]*\)\.ts'#'../data/core/\1'#" \
      -e "s#\(from '\./[a-z-]*\)\.ts'#\1'#" \
      -e "s#\(from '\.\./kit/[a-z-]*\)\.ts'#\1'#" \
      "$dest"
  fi
  if [[ $dest == src/engine/* ]]; then
    sed -i "1i // Generated by scripts/sync-core.sh from $src. Do not edit." "$dest"
  fi
  echo "  $src -> $dest"
done
