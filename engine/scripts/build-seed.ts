// Builds supabase/seed.sql from Ardent Core's demo records
// (core/src/data/mock.ts), so the local engine opens on the same Manchester
// firm the prototypes show. Run from engine/:
//   node --experimental-strip-types scripts/build-seed.ts > supabase/seed.sql
import { writeFileSync } from 'node:fs'
import { certificates, customers, jobs, operators, sites } from '../../core/src/data/mock.ts'

const ORG = 'org_demo'
const PASSWORD = 'ardent-demo'

// Real positions for the demo addresses; the mock holds board positions (0 to 100).
const coords: Record<string, [number, number]> = {
  sit_01: [53.4167, -2.2305],
  sit_02: [53.4555, -2.2246],
  sit_03: [53.4795, -2.2513],
  sit_04: [53.4433, -2.1932],
  sit_05: [53.4247, -2.1781],
  sit_06: [53.4846, -2.2266],
}

// Sign-ins for local development only. Dan owns the firm and works on the tools.
const users = [
  { id: '00000000-0000-4000-a000-000000000001', email: 'dan@demo.ardent.local', role: 'owner', operator: 'opr_01' },
  { id: '00000000-0000-4000-a000-000000000002', email: 'jo@demo.ardent.local', role: 'office', operator: null },
  { id: '00000000-0000-4000-a000-000000000003', email: 'kofi@demo.ardent.local', role: 'field', operator: 'opr_02' },
  { id: '00000000-0000-4000-a000-000000000004', email: 'ryan@demo.ardent.local', role: 'field', operator: 'opr_03' },
  { id: '00000000-0000-4000-a000-000000000005', email: 'tom@demo.ardent.local', role: 'field', operator: 'opr_04' },
]

const q = (v: unknown): string => {
  if (v === undefined || v === null) return 'null'
  if (typeof v === 'number' || typeof v === 'boolean') return String(v)
  if (Array.isArray(v)) return `array[${v.map(q).join(', ')}]::text[]`
  return `'${String(v).replace(/'/g, "''")}'`
}
const row = (...vals: unknown[]) => `  (${vals.map(q).join(', ')})`
const insert = (table: string, cols: string[], rows: string[]) =>
  rows.length ? `insert into public.${table} (${cols.join(', ')}) values\n${rows.join(',\n')};\n` : ''

const out: string[] = [
  '-- Demo data for local development: one Manchester firm, from core/src/data/mock.ts.',
  '-- Generated by scripts/build-seed.ts; edit that, not this file.',
  `-- Sign in as any of: ${users.map((u) => u.email).join(', ')}`,
  `-- Password for all of them: ${PASSWORD}`,
  '',
  'begin;',
  '',
  insert(
    'organisations',
    ['id', 'name', 'slug'],
    [row(ORG, 'Mercer Heating & Electrical', 'mercer-heating')],
  ),
]

for (const u of users) {
  out.push(`insert into auth.users (id, instance_id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, confirmation_token, recovery_token, email_change_token_new, email_change, created_at, updated_at)
values (${q(u.id)}, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', ${q(u.email)},
  extensions.crypt(${q(PASSWORD)}, extensions.gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}', '{}', '', '', '', '', now(), now());
insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (${q(u.id)}, ${q(u.id)}, ${q(u.id)}, ${q(JSON.stringify({ sub: u.id, email: u.email }))}, 'email', now(), now(), now());
`)
}

out.push(insert('memberships', ['org_id', 'user_id', 'role'], users.map((u) => row(ORG, u.id, u.role))))

out.push(
  insert(
    'operators',
    ['id', 'org_id', 'user_id', 'name', 'initials', 'role', 'trades', 'van', 'state', 'eta_minutes'],
    operators.map((o) =>
      row(o.id, ORG, users.find((u) => u.operator === o.id)?.id, o.name, o.initials, o.role, o.trades, o.van, o.state, o.etaMinutes),
    ),
  ),
  insert(
    'operator_registrations',
    ['org_id', 'operator_id', 'body', 'number', 'expires'],
    operators.flatMap((o) => o.registrations.map((r) => row(ORG, o.id, r.body, r.number, r.expires))),
  ),
  insert('customers', ['id', 'org_id', 'name', 'kind', 'phone', 'email'], customers.map((c) => row(c.id, ORG, c.name, c.kind, c.phone, c.email))),
  insert(
    'sites',
    ['id', 'org_id', 'customer_id', 'line1', 'town', 'postcode', 'access_notes', 'latitude', 'longitude'],
    sites.map((s) => row(s.id, ORG, s.customerId, s.line1, s.town, s.postcode, s.accessNotes, ...(coords[s.id] ?? [null, null]))),
  ),
  insert(
    'jobs',
    ['id', 'org_id', 'ref', 'title', 'trade', 'status', 'priority', 'customer_id', 'site_id', 'starts_at', 'ends_at', 'notes'],
    jobs.map((j) => row(j.id, ORG, j.ref, j.title, j.trade, j.status, j.priority, j.customerId, j.siteId, j.start, j.end, j.notes)),
  ),
  insert('job_operators', ['org_id', 'job_id', 'operator_id'], jobs.flatMap((j) => j.operatorIds.map((o) => row(ORG, j.id, o)))),
  insert(
    'job_lines',
    ['id', 'org_id', 'job_id', 'kind', 'description', 'quantity', 'unit_price', 'position'],
    jobs.flatMap((j) => j.lines.map((l, i) => row(l.id, ORG, j.id, l.kind, l.description, l.quantity, l.unitPrice, i))),
  ),
  insert(
    'job_checks',
    ['id', 'org_id', 'job_id', 'key', 'label', 'state', 'detail'],
    jobs.flatMap((j) => j.checks.map((c) => row(`chk_${j.id.slice(4)}_${c.key}`, ORG, j.id, c.key, c.label, c.state, c.detail))),
  ),
  insert(
    'certificates',
    ['id', 'org_id', 'kind', 'site_id', 'job_id', 'issued_on', 'expires_on'],
    certificates.map((c) => row(c.id, ORG, c.kind, c.siteId, c.jobId, c.issued, c.expires)),
  ),
  '-- Where the crew are right now.',
  ...operators
    .filter((o) => o.currentJobId)
    .map((o) => `update public.operators set current_job_id = ${q(o.currentJobId)} where id = ${q(o.id)};`),
  '',
  '-- Carry on numbering after the demo jobs.',
  `insert into public.org_counters (org_id, kind, last) values (${q(ORG)}, 'job', ${Math.max(...jobs.map((j) => Number(j.ref.slice(2))))});`,
  '',
  'commit;',
  '',
)

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'))
