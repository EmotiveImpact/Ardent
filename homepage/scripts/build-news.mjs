// Builds the News page grid and one article page per story (news-<slug>.html)
// from scripts/news-data.mjs. Run: node scripts/build-news.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { stories } from './news-data.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (f) => readFileSync(join(root, f), 'utf8')

const dateHtml = (s) => {
  const [dm, y] = [s.date.slice(0, s.date.lastIndexOf('.')), s.date.slice(s.date.lastIndexOf('.') + 1)]
  return `${s.place ? `${s.place}<br>` : ''}${dm.replace('–', '&ndash;')} &#9632; ${y}`
}
const tagClass = (s, onDark) =>
  s.cat === 'Events' ? 'tag--violet' : onDark ? 'tag--light' : ''

const card = (s) => {
  const href = `news-${s.slug}.html`
  const attrs = `href="${href}" data-cat="${s.cat}"`
  const date = `<p class="card__date mono">${dateHtml(s)}</p>`
  if (s.variant === 'img') return `<a class="card" ${attrs}>
            <figure class="shot card__img" data-img="${s.image}"><img src="images/${s.image}.jpg" alt="${s.alt}" loading="lazy"></figure>
            <span class="tag ${tagClass(s)} mono">${s.cat}</span>
            <h3>${s.title}</h3>
            ${date}
          </a>`
  if (s.variant === 'dark') return `<a class="card card--dark" ${attrs}>
            <span class="tag ${tagClass(s, true)} mono">${s.cat}</span>
            <h3>${s.title}</h3>
            ${date}
          </a>`
  return `<a class="card card--plain" ${attrs}>
            <span class="tag tag--inline ${tagClass(s)} mono">${s.cat}</span>
            <h3>${s.title}</h3>
            ${date}
          </a>`
}

const [lead, ...rest] = stories
const cats = ['All', ...new Set(stories.map((s) => s.cat))]
const count = (c) => (c === 'All' ? stories.length : stories.filter((s) => s.cat === c).length)

const briefForm = (cls) => `<form class="brief ${cls}" data-endpoint="" data-email="hello@ardent.example" novalidate>
          <label class="mono" for="brief-email-${cls}">The Ardent Brief</label>
          <p>One email a month: regulation changes, guides and product news for the trades.</p>
          <div class="brief__row">
            <input id="brief-email-${cls}" name="email" type="email" placeholder="Your email" autocomplete="email" required>
            <button class="btn btn--light" type="submit">Subscribe</button>
          </div>
          <p class="brief__msg mono" role="status" hidden></p>
        </form>`

const grid = `<!-- news:start (generated by scripts/build-news.mjs) -->
        <a class="lead" href="news-${lead.slug}.html" data-cat="${lead.cat}">
          <figure class="shot lead__img" data-img="${lead.image}"><img src="images/${lead.image}.jpg" alt="${lead.alt}"></figure>
          <div class="lead__text">
            <p class="mono"><span class="tag ${tagClass(lead)}">${lead.cat}</span> Latest</p>
            <h2>${lead.title}</h2>
            <p class="lead__dek">${lead.dek}</p>
            <p class="lead__meta mono">${lead.date.replace(/\./g, ' / ')} &#9632; ${lead.read}</p>
          </div>
        </a>
        <div class="news__filter" role="group" aria-label="Filter by topic">
          ${cats.map((c, i) => `<button type="button" class="news__chipbtn${i ? '' : ' is-active'}" data-filter="${c}" aria-pressed="${!i}">${c}<span class="mono">${count(c)}</span></button>`).join('\n          ')}
        </div>
        <div class="news__grid">
          ${rest.map(card).join('\n          ')}
          <div class="card card--brief">
            ${briefForm('brief--card')}
          </div>
        </div>
        <p class="news__empty mono" hidden>Nothing here yet. Try another topic.</p>
        <!-- news:end -->`

const news = read('news.html')
const start = news.indexOf('<!-- news:start')
const from = start >= 0 ? start : news.indexOf('<div class="news__grid">')
const endMark = news.indexOf('<!-- news:end -->')
let to
if (endMark >= 0) to = endMark + '<!-- news:end -->'.length
else {
  // first build: replace the hand-written grid, up to its closing </div>
  const lastCard = news.indexOf('</div>\n      </div>\n    </section>', from)
  to = lastCard + '</div>'.length
}
writeFileSync(join(root, 'news.html'), news.slice(0, from) + grid + news.slice(to))

// Article pages reuse the dark menu and footer from product.html
const base = read('product.html')
const top = base.slice(0, base.indexOf('  <main>')).replace(/ aria-current="page"/g, '')
  .replace('<li><a href="news.html"><span', '<li><a href="news.html" aria-current="page"><span')
  .replace('<li><a href="news.html">News</a></li>', '<li><a href="news.html" aria-current="page">News</a></li>')
const foot = base.slice(base.indexOf('  <footer'))

for (const s of stories) {
  const related = [...stories.filter((o) => o !== s && o.cat === s.cat), ...stories.filter((o) => o !== s && o.cat !== s.cat)].slice(0, 3)
  const head = top
    .replace(/<title>[^<]*<\/title>/, `<title>${s.title.replace(/<[^>]+>/g, '')} | Ardent</title>`)
    .replace(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${s.dek}">`)
    .replace('<body class="page page--ink">', '<body class="page page--ink page--article">')
  const html = `${head}  <main>
    <article class="art">
      <header class="art__head wrap">
        <p class="eyebrow mono"><a href="news.html">News</a> / <a href="news.html#${s.cat}">${s.cat}</a></p>
        <h1>${s.title}</h1>
        <p class="art__dek">${s.dek}</p>
        <p class="art__meta mono"><time datetime="${s.iso}">${s.place ? `${s.place} &#9632; ` : ''}${s.date.replace(/\./g, ' / ').replace('–', '&ndash;')}</time><span>${s.read}</span><span>${s.author}</span></p>
      </header>
      <figure class="shot art__hero wrap" data-img="${s.image}"><img src="images/${s.image}.jpg" alt="${s.alt}"></figure>
      <div class="art__layout wrap">
        <div class="art__body">${s.body}
        </div>
        <aside class="art__aside">
          <div class="art__card">
            <p class="mono">See it on your jobs</p>
            <p>A thirty-minute walkthrough of Ardent, set up for your trade.</p>
            <a class="btn btn--light" href="pricing.html#demo">Book a demo</a>
          </div>
          ${briefForm('brief--aside')}
        </aside>
      </div>
    </article>

    <section class="art-more wrap">
      <p class="eyebrow mono">+ More from Ardent</p>
      <div class="art-more__grid">
        ${related.map((o) => `<a class="art-more__item" href="news-${o.slug}.html">
          <figure class="shot"><img src="images/${o.image}.jpg" alt="" loading="lazy"></figure>
          <p class="mono">${o.cat} &#9632; ${o.date.replace(/\./g, ' / ').replace('–', '&ndash;')}</p>
          <h3>${o.title}</h3>
        </a>`).join('\n        ')}
      </div>
    </section>
  </main>

${foot}`
  writeFileSync(join(root, `news-${s.slug}.html`), html)
}
console.log(`Built the news grid and ${stories.length} article pages`)
